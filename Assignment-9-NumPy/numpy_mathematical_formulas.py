import numpy as np

values=np.array([2,4,6,8,10])
print("Array :",values)
print("\nSquareroot of each element in the array:\n",np.sqrt(values))
print("\nExponential of each element in the array:\n", np.exp(values))
print("\nNatural Logarithm of each element in the array:\n", np.log(values))
print("\nSum of all elements in the array:\n", np.sum(values))
print("\nCumulative sum of all elements in the array:\n", np.cumsum(values))